import { CommandContext, Context, InputFile } from "grammy";
import {
  generateImages,
  ImageGenerationFailedError,
  ImageGenerationUnsupportedError,
  ImageModelNotFoundError,
} from "../../app/services/image-generation-service.js";
import { t } from "../../i18n/index.js";
import { logger } from "../../utils/logger.js";

/** Telegram accepts photos up to 10 MB; larger results are sent as documents. */
const MAX_PHOTO_BYTES = 10 * 1024 * 1024;
const MAX_CAPTION_CHARS = 1_024;
const MAX_ERROR_CHARS = 300;

function extensionForMime(mime: string): string {
  const value = mime.toLowerCase();
  if (value.includes("jpeg") || value.includes("jpg")) return "jpg";
  if (value.includes("webp")) return "webp";
  if (value.includes("gif")) return "gif";
  return "png";
}

function captionFor(prompt: string): string {
  const value = prompt.trim();
  return value.length <= MAX_CAPTION_CHARS ? value : `${value.slice(0, MAX_CAPTION_CHARS - 1)}…`;
}

function failureText(error: unknown): string {
  if (error instanceof ImageGenerationUnsupportedError) return t("image.requires_v2");
  if (error instanceof ImageModelNotFoundError) return t("image.no_model");
  if (error instanceof ImageGenerationFailedError) {
    const message = error.message.slice(0, MAX_ERROR_CHARS);
    return t("image.failed", { error: message });
  }
  return t("image.failed", { error: t("image.unknown_error") });
}

/** `/image <prompt>` generates an image with an image-capable model and sends it to the chat. */
export async function imageCommand(ctx: CommandContext<Context>): Promise<void> {
  const prompt = ctx.match.trim();

  if (!prompt) {
    await ctx.reply(t("image.usage"));
    return;
  }

  const status = await ctx.reply(t("image.generating"));

  try {
    const result = await generateImages({ prompt });

    if (ctx.chat) {
      await ctx.api.deleteMessage(ctx.chat.id, status.message_id).catch(() => undefined);
    }

    for (const [index, image] of result.images.entries()) {
      const filename = image.name ?? `image-${index + 1}.${extensionForMime(image.mime)}`;
      const file = new InputFile(image.buffer, filename);
      const caption = captionFor(prompt);

      if (image.buffer.length > MAX_PHOTO_BYTES) {
        await ctx.replyWithDocument(file, { caption });
      } else {
        await ctx.replyWithPhoto(file, { caption });
      }
    }

    logger.info(
      `[Image] Sent ${result.images.length} image(s) generated by ${result.model.providerID}/${result.model.modelID}`,
    );
  } catch (error) {
    logger.error("[Image] Command failed:", error);
    const text = failureText(error);
    const chatId = ctx.chat?.id;
    if (chatId === undefined) {
      await ctx.reply(text);
      return;
    }
    await ctx.api
      .editMessageText(chatId, status.message_id, text)
      .catch(() => ctx.reply(text));
  }
}
